#!/usr/bin/env python3
"""Generate the 3DS game-data manifest from ReflectionHLE's original definitions.

Only filenames, expected sizes and CRC32 values are extracted; no game data
is redistributed. The original files are under src/backend/gamedefs/.
"""
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve()
REPO = HERE.parents[3]  # platform/3ds/tools/foo -> repo root
OUTPUT = REPO / 'platform/3ds/source/cat3ds_manifest.h'
ROOT = REPO / 'src/backend/gamedefs'
VERSIONS = (
    ('cat3d', 'cat3d100', 'Catacomb 3-D v1.00'),
    ('cat3d', 'cat3d122', 'Catacomb 3-D v1.22'),
    ('catabyss', 'catabyss113', 'Catacomb Abyss v1.13'),
    ('catabyss', 'catabyss124', 'Catacomb Abyss v1.24'),
    ('catarm', 'catarm102', 'Catacomb Armageddon v1.02'),
    ('catapoc', 'catapoc101', 'Catacomb Apocalypse v1.01'),
)
FILES = {
    'cat3d': ROOT / 'be_gamedefs_cat3d.h',
    'catabyss': ROOT / 'be_gamedefs_catabyss.h',
    'catarm': ROOT / 'be_gamedefs_catarm.h',
    'catapoc': ROOT / 'be_gamedefs_catapoc.h',
}


def create_manifest():
    parts = [
        '/* GENERATED by platform/3ds/tools/gen_game_manifest.py.',
        ' * File requirements from ReflectionHLE, Copyright (C) 2014-2026 NY00123.',
        ' * Contains filenames, sizes and CRCs only; no game assets.',
        ' * Do not edit this file by hand.',
        ' */',
        '#ifndef CAT3DS_MANIFEST_H',
        '#define CAT3DS_MANIFEST_H',
        '#include <stdint.h>',
        '#include <stddef.h>',
        'typedef struct Cat3DSRequiredFile {',
        '    const char *name;',
        '    uint32_t size;',
        '    uint32_t crc32;',
        '} Cat3DSRequiredFile;',
        'typedef struct Cat3DSGameVersion {',
        '    int game;',
        '    const char *versionName;',
        '    const Cat3DSRequiredFile *files;',
        '    unsigned fileCount;',
        '} Cat3DSGameVersion;',
    ]
    versions = []
    texts = {key: path.read_text(encoding='utf-8') for key, path in FILES.items()}
    for game, ident, label in VERSIONS:
        source = texts[game]
        # Match a complete required-file array only. Embedded DOS EXE resources
        # (EGAHEAD/EGADICT, etc.) are intentionally not included here.
        array = re.search(
            r'static\s+const\s+BE_GameFileDetails_T\s+'
            r'g_be_reqgameverfiles_' + re.escape(ident) +
            r'\[\]\s*=\s*\{(.*?)\n\s*\};',
            source, re.S)
        if not array:
            raise ValueError(f'Cannot find required files for {ident}')
        items = re.findall(
            r'\{\s*"([A-Za-z0-9_.-]+)"\s*,\s*(\d+)\s*,\s*'
            r'(0x[0-9a-fA-F]+)\s*\}', array.group(1))
        if len(items) < 4:
            raise ValueError(f'Suspiciously short manifest for {ident}: {len(items)} entries')
        key = f'cat3ds_files_{ident}'
        parts.append(f'static const Cat3DSRequiredFile {key}[] = {{')
        for filename, size, crc in items:
            parts.append(f'    {{"{filename}", {size}u, {crc}u}},')
        parts.append('};')
        versions.append((game, label, key, len(items)))
    parts.append('static const Cat3DSGameVersion cat3ds_gameVersions[] = {')
    numbers = {'cat3d': 0, 'catabyss': 1, 'catarm': 2, 'catapoc': 3}
    for game, label, key, count in versions:
        parts.append(f'    {{{numbers[game]}, "{label}", {key}, {count}u}},')
    parts.append('};')
    parts.append('static const unsigned cat3ds_gameVersionCount =')
    parts.append('    (unsigned)(sizeof(cat3ds_gameVersions) / sizeof(cat3ds_gameVersions[0]));')
    parts.append('#endif')
    OUTPUT.write_text('\n'.join(parts) + '\n', encoding='utf-8')
    print('Generated', OUTPUT.relative_to(REPO))
    for _, label, _, count in versions:
        print(f'  {label}: {count} original files')


if __name__ == '__main__':
    try:
        create_manifest()
    except (OSError, ValueError) as exc:
        print('Manifest error:', exc, file=sys.stderr)
        sys.exit(1)
